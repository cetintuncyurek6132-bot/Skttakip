        val b64File = file("${rootDir}/debug.keystore.base64")
        if (b64File.exists()) {
          runCatching {
            val bytes = Base64.getDecoder().decode(b64File.readText().trim())
            ksFile.writeBytes(bytes)
          }
        }
      }
      if (ksFile.exists()) {
        storeFile = ksFile
        storePassword = "android"
        keyAlias = "androiddebugkey"
        keyPassword = "android"
      }
